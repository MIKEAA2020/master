    story.append(Spacer(1, 14))
    if first[0] == "p":
        story.extend(safe_keep_together([heading, rule, Paragraph(no_dash_breaks(first[1]), body_style)]))
        rest = ch["blocks"][1:]
    else:
        story.extend(safe_keep_together([heading, rule]))
        rest = ch["blocks"]
    for block in rest:
        render_block(story, block)
    story.append(Spacer(1, 6))

