def table_header_style(fs):
    return ParagraphStyle(f"TH{fs}", fontName="FreeSerif", fontSize=fs, leading=fs + 3.5,
                          alignment=TA_CENTER, textColor=colors.white)

def table_cell_style(fs):
    return ParagraphStyle(f"TC{fs}", fontName="FreeSerif", fontSize=fs, leading=fs + 3.5,
                          alignment=TA_LEFT, textColor=TEXT_PRIMARY)

stat_style = ParagraphStyle("StatBig", fontName="FreeSerif", fontSize=19, leading=23,
                            alignment=TA_CENTER, textColor=ACCENT)
stat_label_style = ParagraphStyle("StatLabel", fontName="FreeSerif", fontSize=8, leading=11,
                                  alignment=TA_CENTER, textColor=TEXT_MUTED)

# ---------------------------------------------------------------- helpers
def add_heading(text, style, level=0):
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def no_dash_breaks(text):
    # bind em-dashes to the preceding word so no line starts with a dash
    return text.replace(" — ", "\u00a0— ")

def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)

def embed_image(path, max_width=None, max_height=None):
    if max_width is None:
        max_width = AVAIL_W
    if max_height is None:
        max_height = 400
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow, max_height / oh, 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)

def build_table(key):
    spec = TABLES[key]
    fs = spec["font"]
    ths, tcs = table_header_style(fs), table_cell_style(fs)
    data = [[Paragraph("<b>%s</b>" % h, ths) for h in spec["header"]]]
    for row in spec["rows"]:
        data.append([Paragraph(no_dash_breaks(c), tcs) for c in row])
    col_widths = [r * AVAIL_W for r in spec["ratios"]]
    assert sum(col_widths) <= AVAIL_W + 0.5, "table %s overflows" % key
    t = Table(data, colWidths=col_widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("TEXTCOLOR", (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t

def callout(text):
    inner = Paragraph(no_dash_breaks(text), quote_style)
    t = Table([[inner]], colWidths=[AVAIL_W * 0.94], hAlign="CENTER")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("LINEBEFORE", (0, 0), (0, -1), 3, ACCENT),
        ("LEFTPADDING", (0, 0), (-1, -1), 14),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return t

def stats_row(items):
    cell_w = AVAIL_W / 3.0
    row = [[Paragraph("<b>%s</b>" % val, stat_style),
            Paragraph(label, stat_label_style)] for (val, label) in items]
    t = Table([row], colWidths=[cell_w] * 3, hAlign="CENTER")
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("BOX", (0, 0), (-1, -1), 0.75, ACCENT),
        ("LINEBEFORE", (1, 0), (2, 0), 0.5, BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 9),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
    ]))
    return t

def render_block(story, block):
    kind, val = block
    if kind == "p":
        story.append(Paragraph(no_dash_breaks(val), body_style))
    elif kind == "quote":
        story.append(Spacer(1, 8))
        story.append(callout(val))
        story.append(Spacer(1, 14))
    elif kind == "ol":
        for i, item in enumerate(val, 1):
            story.append(Paragraph("%d.  %s" % (i, item), list_style))
        story.append(Spacer(1, 4))
    elif kind == "table":
        story.append(Spacer(1, 16))
        tbl = build_table(val)
        cap = Paragraph(TABLES[val]["caption"], caption_style)
        if len(TABLES[val]["rows"]) <= 8:
            story.extend(safe_keep_together([tbl, cap]))
        else:
            story.append(tbl)
            story.append(Spacer(1, 2))
            story.append(cap)
        story.append(Spacer(1, 14))
    elif kind == "stats":
        story.append(Spacer(1, 10))
        story.append(stats_row(val))
        story.append(Spacer(1, 12))
    elif kind == "figure":
        path, capt = FIGURES[val]
        img = embed_image(path, max_width=AVAIL_W, max_height=400)
        cap = Paragraph(capt, caption_style)
        story.append(Spacer(1, 18))
        story.extend(safe_keep_together([img, Spacer(1, 8), cap]))
        story.append(Spacer(1, 16))

